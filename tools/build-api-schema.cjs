/*
 * Builds app/datamodel/ApiSchema.js from a Roblox API dump.
 *
 * Sources (in order of preference):
 *   1. CLI path:  node tools/build-api-schema.cjs path/to/API-Dump.json
 *   2. tools/_api-dump-latest.json  (download from MoraineArchive or rbxcdn)
 *   3. The dump embedded in app/thirdparty/rbxBinaryParser.js (legacy)
 *
 * Recommended refresh (official dump mirrored by Moraine):
 *   curl -L -o tools/_api-dump-latest.json ^
 *     https://raw.githubusercontent.com/MoraineArchive/RobloxStudio-Datamining/main/current/API/API-Dump.json
 *   node tools/build-api-schema.cjs
 *
 * Moraine NOTICE: the dump is Roblox IP archived for research/interop. We only
 * keep a compressed schema (class/property/enum names + types), not Studio assets.
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const outPath = path.join(root, "app/datamodel/ApiSchema.js");
const cachedDump = path.join(root, "tools/_api-dump-latest.json");

function loadOfficialDump(filePath) {
	const raw = JSON.parse(fs.readFileSync(filePath, "utf8"));
	if (!Array.isArray(raw.Classes) || !Array.isArray(raw.Enums)) {
		throw new Error(`${filePath} is not a Roblox API-Dump.json (missing Classes/Enums)`);
	}
	return { classes: raw.Classes, enums: raw.Enums, source: filePath };
}

function loadEmbeddedDump() {
	const src = fs.readFileSync(path.join(root, "app/thirdparty/rbxBinaryParser.js"), "utf8");
	const start = src.indexOf("JSON.parse('") + 12;
	let end = start;
	while (end < src.length) {
		if (src[end] === "\\") { end += 2; continue; }
		if (src[end] === "'") break;
		end++;
	}
	// eslint-disable-next-line no-eval
	const dump = JSON.parse(eval("'" + src.slice(start, end) + "'"));
	// Compact format used by rbxBinaryParser: PZ = classes, Yb = enums
	const classes = dump.PZ.map((cls) => ({
		Name: cls.Name,
		Superclass: cls.Superclass,
		Tags: cls.Tags,
		Members: cls.Members
	}));
	const enums = dump.Yb.map((e) => ({ Name: e.Name, Items: e.Items }));
	return { classes, enums, source: "app/thirdparty/rbxBinaryParser.js (embedded)" };
}

function build(classesIn, enumsIn) {
	const classes = {};
	for (const cls of classesIn) {
		const props = {};
		const scriptable = {};
		const events = [];
		const functions = [];
		for (const m of cls.Members || []) {
			if (m.MemberType === "Event") events.push(m.Name);
			if (m.MemberType === "Function") functions.push(m.Name);
			if (m.MemberType !== "Property") continue;
			const type = m.ValueType.Category === "Enum" ? `Enum:${m.ValueType.Name}`
				: m.ValueType.Category === "Class" ? "Ref"
				: m.ValueType.Name;
			if (m.Serialization && m.Serialization.CanSave) props[m.Name] = type;
			const hidden = (m.Tags || []).includes("Hidden") || (m.Tags || []).includes("NotScriptable");
			if (!hidden) scriptable[m.Name] = type;
		}
		classes[cls.Name] = {
			s: cls.Superclass && cls.Superclass !== "<<<ROOT>>>" ? cls.Superclass : null,
			p: props,
			r: scriptable,
			e: events,
			f: functions,
			...((cls.Tags || []).includes("NotCreatable") ? { nc: 1 } : {}),
			...((cls.Tags || []).includes("Service") ? { svc: 1 } : {})
		};
	}

	const enums = {};
	for (const e of enumsIn) {
		enums[e.Name] = Object.fromEntries((e.Items || []).map((i) => [i.Name, i.Value]));
	}
	return { classes, enums };
}

const argPath = process.argv[2] && path.resolve(process.argv[2]);
let loaded;
if (argPath && fs.existsSync(argPath)) loaded = loadOfficialDump(argPath);
else if (fs.existsSync(cachedDump)) loaded = loadOfficialDump(cachedDump);
else loaded = loadEmbeddedDump();

const { classes, enums } = build(loaded.classes, loaded.enums);
const out = `/* Generated by tools/build-api-schema.cjs — do not edit.
 * Source: ${loaded.source.replace(/\\/g, "/")}
 * Classes: ${Object.keys(classes).length} · Enums: ${Object.keys(enums).length}
 */
export const API_CLASSES = ${JSON.stringify(classes)};
export const API_ENUMS = ${JSON.stringify(enums)};
`;
fs.writeFileSync(outPath, out);
console.log(`ApiSchema.js from ${loaded.source}`);
console.log(`  ${Object.keys(classes).length} classes, ${Object.keys(enums).length} enums, ${(out.length / 1024).toFixed(0)} KB`);
